// Generates TypeScript types for every operation (request/result) and node kind (params) from the
// committed JSON Schemas under schemas/v1 (written by `jd schema --write schemas/v1`).
// Usage: node scripts/gen-types.mjs   → src/lib/ops.gen.ts (CI fails when it is stale).
// Handles the subset schemars emits for our types: objects, arrays/tuples, enums (enum / oneOf
// const), anyOf-with-null, $ref into $defs, maps (additionalProperties), primitives.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../../..");
const opsDir = path.join(root, "schemas/v1/ops");
const out = path.join(here, "../src/lib/ops.gen.ts");

const named = new Map(); // type name → TS body (deduped; conflicting shapes get a numeric suffix)
const nameFor = (base, body) => {
  let name = base.replace(/[^A-Za-z0-9_]/g, "_");
  let i = 2;
  while (named.has(name) && named.get(name) !== body) name = `${base}${i++}`;
  named.set(name, body);
  return name;
};

function ts(schema, defs) {
  if (schema.$ref) {
    const key = schema.$ref.split("/").pop();
    const def = defs[key];
    if (!def) return "unknown";
    const body = ts(def, defs);
    return nameFor(key, body);
  }
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (schema.oneOf && schema.oneOf.every((o) => "const" in o)) return schema.oneOf.map((o) => JSON.stringify(o.const)).join(" | ");
  if (schema.anyOf || schema.oneOf) return (schema.anyOf ?? schema.oneOf).map((o) => ts(o, defs)).join(" | ");
  const types = Array.isArray(schema.type) ? schema.type : [schema.type];
  const parts = types.map((t) => {
    switch (t) {
      case "string":
        return "string";
      case "integer":
      case "number":
        return "number";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array": {
        const item = schema.items ? ts(schema.items, defs) : "unknown";
        if (schema.minItems !== undefined && schema.minItems === schema.maxItems) return `[${Array(schema.minItems).fill(item).join(", ")}]`;
        return `${item.includes(" ") ? `(${item})` : item}[]`;
      }
      case "object": {
        if (!schema.properties) {
          const v = schema.additionalProperties && typeof schema.additionalProperties === "object" ? ts(schema.additionalProperties, defs) : "unknown";
          return `Record<string, ${v}>`;
        }
        const req = new Set(schema.required ?? []);
        const fields = Object.entries(schema.properties).map(([k, p]) => {
          const doc = p.description ? `  /** ${p.description.replace(/\*\//g, "* /")} */\n` : "";
          return `${doc}  ${JSON.stringify(k)}${req.has(k) ? "" : "?"}: ${ts(p, defs, k)};`;
        });
        return `{\n${fields.join("\n")}\n}`;
      }
      default:
        return "unknown";
    }
  });
  return [...new Set(parts)].join(" | ");
}

const index = JSON.parse(readFileSync(path.join(opsDir, "index.json"), "utf8"));
const ops = [];
for (const { id, description } of index) {
  const req = JSON.parse(readFileSync(path.join(opsDir, `${id}.request.json`), "utf8"));
  const res = JSON.parse(readFileSync(path.join(opsDir, `${id}.result.json`), "utf8"));
  const base = id.split(".").map((s) => s[0].toUpperCase() + s.slice(1).replace(/_(\w)/g, (_, c) => c.toUpperCase())).join("");
  const reqName = nameFor(`${base}Request`, ts(req, req.$defs ?? {}, base));
  const resName = nameFor(`${base}Result`, ts(res, res.$defs ?? {}, base));
  ops.push({ id, description, reqName, resName });
}
const kinds = JSON.parse(readFileSync(path.join(root, "schemas/v1/graph/node-kinds.json"), "utf8"));
const kindTypes = kinds.map((k) => {
  const base = `NodeParams_${k.kind.replace(/[^A-Za-z0-9]+/g, "_")}`;
  return { kind: k.kind, name: nameFor(base, ts(k.param_schema, k.param_schema.$defs ?? {}, base)) };
});

let src = `// GENERATED by scripts/gen-types.mjs from schemas/v1 — do not edit (run \`pnpm types:gen\`).\n/* eslint-disable */\n\n`;
for (const [name, body] of named) src += `export type ${name} = ${body};\n\n`;
src += `/** Request and result types of every core operation, keyed by op id. */\nexport interface JdOps {\n`;
for (const o of ops) src += `  /** ${o.description} */\n  ${JSON.stringify(o.id)}: { request: ${o.reqName}; result: ${o.resName} };\n`;
src += `}\n\nexport type OpId = keyof JdOps;\n\n/** Parameter types of every built-in node kind. */\nexport interface NodeKinds {\n`;
for (const k of kindTypes) src += `  ${JSON.stringify(k.kind)}: ${k.name};\n`;
src += `}\n`;
writeFileSync(out, src);
console.log(`wrote ${path.relative(root, out)}: ${ops.length} ops, ${kindTypes.length} node kinds, ${named.size} types`);
